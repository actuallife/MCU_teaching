   f"（{T_MAX} − {T_MIN}）÷ {T_K} = {T_RANGE} ÷ {T_K} = {fmt(T_RANGE / T_K, 2)} → 取 <b>{T_W}</b> 分。<br>"
   f"一定要<b>向上</b>取整，取 {fmt(T_RANGE / T_K, 1)} 或更小會蓋不住全部資料，最大值會掉在組外。<br>"
