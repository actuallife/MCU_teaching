# ═══════════════════════════════════════════════ 情境一：付款方式（類別資料）
PAY_L = ["信用卡", "行動支付", "貨到付款", "ATM 轉帳"]
PAY_F = [88, 56, 36, 20]
PAY_N = sum(PAY_F)
PAY_REL = [f / PAY_N for f in PAY_F]
PAY_PCT = [p * 100 for p in PAY_REL]
PAY_DEG = [p * 360 for p in PAY_REL]

# ═══════════════════════════════════════════════ 情境二：客服處理時間（數量資料）
TIME = [2, 3, 4, 4, 5, 6, 6, 7, 7, 8, 8, 9, 9, 10, 10, 11,
        12, 12, 13, 14, 15, 16, 17, 19, 21, 22, 24, 26, 28, 29]
T_N = len(TIME)
T_MIN, T_MAX = min(TIME), max(TIME)
T_RANGE = T_MAX - T_MIN
T_K = 6                                        # 組數
T_W = ceil(T_RANGE / T_K)                      # 組距（向上取整）
T_EDGES = [(0, 4), (5, 9), (10, 14), (15, 19), (20, 24), (25, 29)]
T_FREQ = [sum(1 for x in TIME if a <= x <= b) for a, b in T_EDGES]
T_MIDS = [(a + b) / 2 for a, b in T_EDGES]
T_REL = [f / T_N for f in T_FREQ]
T_CUM = [sum(T_FREQ[:i + 1]) for i in range(len(T_FREQ))]
T_CUMREL = [c / T_N for c in T_CUM]
T_MODAL = T_FREQ.index(max(T_FREQ))            # 眾數組的索引

# ═══════════════════════════════════════════════ 情境三：裝置 × 是否完成購買
DEV_L = ["手機", "桌機"]
BUY = [[96, 144], [36, 24]]                    # [完成, 未完成]
DEV_TOT = [sum(r_) for r_ in BUY]
COL_TOT = [sum(r_[j] for r_ in BUY) for j in (0, 1)]
GRAND = sum(DEV_TOT)
DEV_RATE = [BUY[i][0] / DEV_TOT[i] * 100 for i in range(2)]

# ╔══════════════════════════════════════════════════════════════════╗
# ║                            選 擇 題                               ║
