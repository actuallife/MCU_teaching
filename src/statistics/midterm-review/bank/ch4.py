PA_F = 0.92                                 # 異常時被標記
PA_nF = 0.05                                # 正常時被誤標
J_F = PF * PA_F
J_nF = (1 - PF) * PA_nF
PA = J_F + J_nF
PF_A = J_F / PA

# ═══════════════════════════════════════ 情境三：計數法則
