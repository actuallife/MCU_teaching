N_STU = 400
TAB = [[168, 112],      # 修過程式設計：通過、未通過
       [36, 84]]        # 沒修過
ROW = [sum(x) for x in TAB]                 # 280, 120
COL = [sum(x[j] for x in TAB) for j in (0, 1)]
